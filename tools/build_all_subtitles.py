ted_zh_path = r"c:\Antigravity\EA\curriculum_data\ted_transcript_zh.txt"
if os.path.exists(ted_zh_path):
    with open(ted_zh_path, "r", encoding="utf-8") as f:
        full_ted_zh = f.read().strip()
    
    # Let's map TED videos
    ted_videos = [
        "Slide-045_VID-001_TED-Talk-Part-1_Showing-Up",
        "Slide-088_VID-001_TED-Talk-Part-2_Stepping-Out",
        "Slide-149_VID-001_TED-Talk-Part-3_Walking-Your-Why",
        "Slide-179_VID-001_TED-Talk-Part-4_Moving-On",
        "TED-Talk_Full_The-Gift-and-Power-of-Emotional-Courage"
    ]
    
    # Build clean sentence chunks from official TED Chinese text
    raw_sentences = [s.strip() for s in full_ted_zh.replace("。", "。\n").replace("！", "！\n").replace("？", "？\n").split("\n") if s.strip()]
    print(f"Total TED Chinese sentences: {len(raw_sentences)}")
    
    for tv in ted_videos:
        jp = os.path.join(transcripts_dir, f"{tv}.json")
        out_vtt = os.path.join(media_dir, f"{tv}.zh.vtt")
        if not os.path.exists(jp):
            continue
        with open(jp, "r", encoding="utf-8") as f:
            data = json.load(f)
        segs = data.get("segments", [])
        
        # Segment-proportional mapping to official sentences
        vtt_lines = ["WEBVTT\n"]
        n_segs = len(segs)
        
        if "Part-1" in tv:
            part_sentences = raw_sentences[:len(raw_sentences)*10//17]
        elif "Part-2" in tv:
            part_sentences = raw_sentences[len(raw_sentences)*10//17 : len(raw_sentences)*14//17]
